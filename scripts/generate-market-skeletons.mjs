import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

// Vector silhouettes from the transparent covers; source images remain untouched.
const catalogue = [
  "glock18",
  "weapon-case",
  "briefcase",
  "bulletproof-umbrella",
  "to-the-moon-visa",
  "bitcoin",
  "ethereum",
];
const masks = {};
for (const id of catalogue) {
  const directory = path.resolve("public/marketplace", id);
  const { data, info } = await sharp(path.join(directory, "cover.webp"))
    .resize({ width: 278 })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let active = new Map();
  const rectangles = [];
  for (let y = 0; y <= info.height; y++) {
    const runs = new Map();
    let x = 0;
    while (y < info.height && x < info.width) {
      if (data[(y * info.width + x) * info.channels + 3] < 32) {
        x++;
        continue;
      }
      const start = x++;
      while (x < info.width && data[(y * info.width + x) * info.channels + 3] >= 32) x++;
      const key = `${start}:${x}`;
      const previous = active.get(key);
      runs.set(
        key,
        previous
          ? { ...previous, height: previous.height + 1 }
          : { x: start, y, width: x - start, height: 1 },
      );
    }
    for (const [key, rectangle] of active) if (!runs.has(key)) rectangles.push(rectangle);
    active = runs;
  }
  const outline = rectangles
    .map(({ x, y, width, height }) => `M${x} ${y}h${width}v${height}h-${width}z`)
    .join("");
  await fs.writeFile(
    path.join(directory, "skeleton.svg"),
    `<svg xmlns="http://www.w3.org/2000/svg" width="556" height="384" viewBox="0 0 ${info.width} ${info.height}"><path fill="white" d="${outline}"/></svg>\n`,
  );
  process.stdout.write(`${id}: ${rectangles.length} outline segments\n`);
  masks[id] =
    `data:image/svg+xml,${encodeURIComponent(await fs.readFile(path.join(directory, "skeleton.svg"), "utf8"))}`;
}

// Canopy silhouette for the Home hero's nearly vertical camera.
